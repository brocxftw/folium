github_latest_tag() {
  curl -fsSL --max-time 20 \
    -H "Accept: application/vnd.github+json" \
    "https://api.github.com/repos/${FOLIUM_GITHUB_REPO}/releases/latest" \
    | python3 -c 'import json,sys; print(json.load(sys.stdin)["tag_name"])'
}

github_release_tags() {
  curl -fsSL --max-time 20 \
    -H "Accept: application/vnd.github+json" \
    "https://api.github.com/repos/${FOLIUM_GITHUB_REPO}/releases?per_page=15" \
    | python3 -c 'import json,sys
for rel in json.load(sys.stdin):
    if rel.get("draft") or rel.get("prerelease"):
        continue
    print(rel["tag_name"])
'
}

github_asset_url() {
  local tag="$1"
  local name="$2"
  printf 'https://github.com/%s/releases/download/%s/%s' "${FOLIUM_GITHUB_REPO}" "${tag}" "${name}"
}

config_download() {
  local url="$1"
  local dest="$2"
  log_cmd "curl ${url} -> ${dest}"
  curl -fsSL --max-time 60 -o "${dest}" "${url}"
}

config_download_env_example() {
  local tag="$1"
  local dest="$2"
  local name
  for name in env.example default.env.example .env.example; do
    if config_download "$(github_asset_url "${tag}" "${name}")" "${dest}"; then
      log_info "downloaded env template as ${name}"
      return 0
    fi
  done
  return 1
}

config_generate_secret() {
  local bytes="${1:-32}"
  openssl rand -hex "${bytes}"
}

config_postgres_password_ok() {
  local pw="${1:-}"
  [[ -n "${pw}" ]] || return 1
  [[ "${pw}" != *[@:/\#\?]* ]]
}

