config_env_get() {
  local key="$1"
  local file="${2:-${FOLIUM_INSTALL_DIR}/.env}"
  [[ -f "${file}" ]] || return 1
  python3 - "${file}" "${key}" <<'PY'
import sys
path, key = sys.argv[1], sys.argv[2]
for raw in open(path, encoding="utf-8"):
    line = raw.strip()
    if not line or line.startswith("#") or "=" not in line:
        continue
    k, v = line.split("=", 1)
    if k == key:
        print(v, end="")
        break
else:
    sys.exit(1)
PY
}

config_env_set() {
  local key="$1"
  local value="$2"
  local file="${3:-${FOLIUM_INSTALL_DIR}/.env}"
  [[ -f "${file}" ]] || return 1
  python3 - "${file}" "${key}" "${value}" <<'PY'
import sys
path, key, value = sys.argv[1], sys.argv[2], sys.argv[3]
lines = open(path, encoding="utf-8").read().splitlines(True)
out = []
found = False
for line in lines:
    raw = line.strip()
    if raw and not raw.startswith("#") and "=" in raw:
        k, _ = raw.split("=", 1)
        if k == key:
            out.append(f"{key}={value}\n")
            found = True
            continue
    out.append(line)
if not found:
    if out and not out[-1].endswith("\n"):
        out[-1] = out[-1] + "\n"
    out.append(f"{key}={value}\n")
with open(path, "w", encoding="utf-8") as fh:
    fh.writelines(out)
PY
  chmod 600 "${file}"
  log_info "updated .env key=${key}"
}

config_strip_compose_ports() {
  local file="$1"
  python3 - "${file}" <<'PY'
import re, sys
path = sys.argv[1]
with open(path, encoding="utf-8") as fh:
    lines = fh.readlines()
out = []
current = None
i = 0
while i < len(lines):
    line = lines[i]
    m = re.match(r"^  ([a-zA-Z0-9_]+):\s*$", line)
    if m:
        current = m.group(1)
        out.append(line)
        i += 1
        continue
    if current in {"api", "web"} and re.match(r"^    ports:\s*$", line):
        i += 1
        while i < len(lines) and re.match(r"^      - ", lines[i]):
            i += 1
        continue
    out.append(line)
    i += 1
with open(path, "w", encoding="utf-8") as fh:
    fh.writelines(out)
PY
}

config_write_override() {
  local dest="${FOLIUM_INSTALL_DIR}/docker-compose.override.yml"
  local extra_gid="${FOLIUM_EXTRA_GID:-}"
  local expose="${FOLIUM_EXPOSE_API:-0}"
  python3 - "${dest}" "${expose}" "${extra_gid}" <<'PY'
import sys
dest, expose, extra = sys.argv[1], sys.argv[2], sys.argv[3]
lines = [
    "# Generated by the Folium installer. Ports and optional extra GID only.",
    "# Do not store secrets here.",
    "services:",
    "  web:",
    "    ports:",
    '      - "${FOLIUM_BIND}:${FOLIUM_HTTP_PORT}:80"',
]
if expose == "1":
    lines += [
        "  api:",
        "    ports:",
        '      - "${FOLIUM_BIND}:${FOLIUM_API_PORT}:8000"',
    ]
    if extra:
        lines += ["    group_add:", f'      - "{extra}"']
elif extra:
    lines += ["  api:", "    group_add:", f'      - "{extra}"']
if extra:
    lines += ["  worker:", "    group_add:", f'      - "{extra}"']
text = "\n".join(lines) + "\n"
with open(dest, "w", encoding="utf-8") as fh:
    fh.write(text)
PY
  log_info "wrote docker-compose.override.yml"
}

config_write_source_overlay() {
  local dest="${FOLIUM_INSTALL_DIR}/compose.source.yaml"
  cat >"${dest}" <<'EOF'
# Generated by the Folium installer for source builds.
# Build context is INSTALL_DIR/src (git clone of the tagged release).
# Does not publish Postgres.
services:
  api:
    build:
      context: ./src
      dockerfile: docker/Dockerfile.backend
      args:
        FOLIUM_VERSION: ${FOLIUM_VERSION}
        FOLIUM_BUILD_REVISION: ${FOLIUM_BUILD_REVISION:-}
        FOLIUM_BUILD_DATE: ${FOLIUM_BUILD_DATE:-}
    image: ghcr.io/brocxftw/folium-backend:${FOLIUM_VERSION}
  worker:
    build:
      context: ./src
      dockerfile: docker/Dockerfile.backend
      args:
        FOLIUM_VERSION: ${FOLIUM_VERSION}
        FOLIUM_BUILD_REVISION: ${FOLIUM_BUILD_REVISION:-}
        FOLIUM_BUILD_DATE: ${FOLIUM_BUILD_DATE:-}
    image: ghcr.io/brocxftw/folium-backend:${FOLIUM_VERSION}
  web:
    build:
      context: ./src
      dockerfile: docker/Dockerfile.frontend
      args:
        FOLIUM_VERSION: ${FOLIUM_VERSION}
        FOLIUM_BUILD_REVISION: ${FOLIUM_BUILD_REVISION:-}
        FOLIUM_BUILD_DATE: ${FOLIUM_BUILD_DATE:-}
    image: ghcr.io/brocxftw/folium-web:${FOLIUM_VERSION}
EOF
  log_info "wrote compose.source.yaml"
}

config_backup_install_dir() {
  local src="${FOLIUM_INSTALL_DIR}"
  local stamp backup
  [[ -d "${src}" ]] || return 0
  stamp="$(date -u +%Y%m%d-%H%M%S)"
  backup="${src}/backups/${stamp}"
  mkdir -p "${backup}"
  chmod 700 "${backup}"
  local f
  for f in .env docker-compose.yml docker-compose.override.yml compose.source.yaml install-state.json; do
    if [[ -f "${src}/${f}" ]]; then
      cp -a "${src}/${f}" "${backup}/${f}"
    fi
  done
  if [[ -f "${backup}/.env" ]]; then
    chmod 600 "${backup}/.env"
  fi
  log_info "backed up existing files to backups/${stamp}"
}

config_compose_validate() {
  local out
  if ! out="$(folium_compose config 2>&1)"; then
    log_error "docker compose config failed"
    printf '%s\n' "${out}" | _folium_redact >>"${FOLIUM_LOG_FILE:-/dev/null}"
    return 1
  fi
  log_info "docker compose config ok"
  return 0
}

